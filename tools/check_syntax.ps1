# check_syntax.ps1 -- Lua 5.3 syntax check (authoritative) + self-check
#
# WHY THIS SCRIPT EXISTS (2026-10-27, a real burn failure):
#
#   The local luac is Lua 5.1 (`C:\Program Files (x86)\Lua\5.1\luac.exe`)
#   but the firmware runs Lua 5.3. 5.1's luac cannot parse 5.3 syntax --
#   `//` `~` `<<` `>>` -- and lua/bus/mbus.lua uses `crc // 2` and `~ poly`
#   for its CRC table, so 5.1 ALWAYS reports a false error there.
#
#   The workaround that was used to silence that false positive ALSO hid
#   real errors:
#       cmd /c "luac -p x.lua 2>&1 & echo E=%ERRORLEVEL!"
#   expands %ERRORLEVEL% at PARSE time, so it yields the exit code of the
#   PREVIOUS command -- always 0. The check "passed" while the file had a
#   duplicated `return true` (12-fix), which only blew up at flash time:
#       poll.lua:505: 'end' expected (to close 'function' at line 478)
#   (Lua rule: `return` must be the LAST statement of a block)
#
#   => A syntax check must use the firmware's own 5.3 core. That core is the
#      Luatools LuatOS PC simulator. loadfile() compiles without running, so
#      every file can be checked safely.
#
# HOW IT WORKS:
#   1. stage the simulator into %TEMP% (once)
#   2. mirror the sources to <staging>\lua\
#   3. write a generated main.lua that lists the files as LITERALS
#      (the simulator's dependency-trim scanner only keeps files it can see
#      as literals in main.lua -- a list passed via env var is invisible
#      to it, and the files get trimmed away)
#   4. run the simulator; exit code 0 = all files compile
#   5. self-check: inject a deliberately broken file into the SAME list and
#      confirm the checker reports it (a checker that cannot fail is worse
#      than no checker at all)
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File tools\check_syntax.ps1
#   powershell -ExecutionPolicy Bypass -File tools\check_syntax.ps1 -Root build\lua_burn
param(
    [string]$Root = "lua",
    [switch]$NoSelfCheck
)

$ErrorActionPreference = "Continue"

# ---- resolve paths relative to the repo root, not the caller's cwd ----
$repo = Split-Path -Parent $PSScriptRoot
if (-not (Test-Path $Root)) {
    $alt = Join-Path $repo $Root
    if (Test-Path $alt) { $Root = $alt }
}
if (-not (Test-Path $Root)) { Write-Host "找不到目录: $Root" -ForegroundColor Red; exit 2 }
$srcFull = (Resolve-Path $Root).Path

# ---- find the simulator ----
$sim = $null
$pcRoot = "D:\Luatools\resource\LuatOS_PC"
if (Test-Path $pcRoot) {
    $d = Get-ChildItem $pcRoot -Directory -Filter "LuatOS-SoC_*_PC" -ErrorAction SilentlyContinue |
         Sort-Object Name -Descending | Select-Object -First 1
    if ($d) { $sim = $d.FullName }
}
if (-not $sim) { Write-Host "找不到 LuatOS PC 模拟器 (D:\Luatools\resource\LuatOS_PC)" -ForegroundColor Red; exit 2 }
$simExe = Join-Path $sim "luatos-pc.exe"
if (-not (Test-Path $simExe)) { Write-Host "模拟器缺 luatos-pc.exe: $sim" -ForegroundColor Red; exit 2 }

# ---- collect the files to check ----
$files = Get-ChildItem $srcFull -Recurse -File -Filter *.lua | Sort-Object FullName
if ($files.Count -eq 0) { Write-Host "没有 .lua 文件: $srcFull" -ForegroundColor Red; exit 2 }

# ---- staging ----
$scr = Join-Path $env:TEMP "vkbox_lua_pc_syntax"
if (-not (Test-Path (Join-Path $scr "luatos-pc.exe"))) {
    Write-Host "[setup] 复制模拟器到 $scr (只做一次, 慢)"
    robocopy $sim $scr /E /XD demo pclogs | Out-Null
}
$dst = Join-Path $scr "lua"
if (Test-Path $dst) { Remove-Item $dst -Recurse -Force -ErrorAction SilentlyContinue }
robocopy $srcFull $dst /E /NJH /NJS /NDL /NFL | Out-Null

# the device entry point collides with the generated main.lua in the
# simulator's dependency-trim mode ("不允许重名文件 main.lua"), so stage it
# under another name -- loadfile only cares about the bytes, not the name
$devMain = Join-Path $dst "main.lua"
if (Test-Path $devMain) {
    Move-Item $devMain (Join-Path $dst "_entry.lua") -Force
}

# ---- build the literal file list for the generated main.lua ----
$entries = @()
foreach ($f in $files) {
    $rel = $f.FullName.Substring($srcFull.Length).TrimStart('\').Replace('\', '/')
    if ($rel -eq "main.lua") { $rel = "_entry.lua" }
    $entries += ("lua/" + $rel)
}

function Write-CheckerMain([string[]]$list) {
    $listText = ($list | ForEach-Object { '  "' + $_ + '",' }) -join "`n"
    $mainText = @"
-- GENERATED by tools/check_syntax.ps1 -- do not edit
local sys = require "sys"
local FILES = {
$listText
}
sys.taskInit(function()
    local n, bad = 0, 0
    for _, p in ipairs(FILES) do
        n = n + 1
        local chunk, err = loadfile(p)
        if not chunk then
            bad = bad + 1
            print("SYNTAX FAIL: " .. p .. "  " .. tostring(err))
        end
    end
    print(string.format("== syntax checked %d files (Lua 5.3), failed %d", n, bad))
    if bad > 0 then os.exit(1) end
    os.exit(0)
end)
sys.run()
"@
    [System.IO.File]::WriteAllText((Join-Path $scr "main.lua"), $mainText, (New-Object System.Text.UTF8Encoding($false)))
}

function Invoke-Simulator {
    Push-Location $scr
    $o = cmd /c "`"$simExe`" . 2>&1"
    $rc = $LASTEXITCODE
    Pop-Location
    return @{ Out = $o; Rc = $rc }
}

# ---- pass 1: the real files ----
Write-CheckerMain $entries
$r = Invoke-Simulator
$r.Out | Select-String -Pattern 'SYNTAX FAIL|syntax checked' | ForEach-Object { Write-Host $_.Line }
Write-Host ("检查 {0} 个文件 ({1}), 模拟器退出码 {2}" -f $entries.Count, $Root, $r.Rc) -ForegroundColor $(if ($r.Rc -eq 0) { "Green" } else { "Red" })
if ($r.Rc -ne 0) { exit 1 }

# ---- pass 2: self-check -- prove the checker can actually fail ----
if (-not $NoSelfCheck) {
    $relBroken = "lua/_selfcheck_broken.lua"
    $broken = Join-Path $scr $relBroken.Replace("/", "\")
    # duplicated `return` -- exactly the 12-fix bug
    [System.IO.File]::WriteAllText($broken, "local function f()`n  return true`n  return true`nend`nreturn f`n")
    Write-CheckerMain ($entries + $relBroken)
    $r2 = Invoke-Simulator
    Remove-Item $broken -Force -ErrorAction SilentlyContinue
    $hit = ($r2.Out | Select-String -Pattern '_selfcheck_broken.lua').Count
    if ($r2.Rc -ne 0 -and $hit -gt 0) {
        Write-Host "自检 OK: 故意写坏的样例被正确判为 FAIL (exit=$($r2.Rc))" -ForegroundColor Green
    } else {
        Write-Host "自检失败: 校验器抓不到语法错误, 结果不可信! (exit=$($r2.Rc), 命中=$hit)" -ForegroundColor Red
        exit 3
    }
}
exit 0
